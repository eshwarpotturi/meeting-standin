// Joins the shared parts into one file you paste into the Meet tab's console: standin-chat.js
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('./', import.meta.url);
const parts = ['../extension/src/log.js', '../extension/src/config.js', '../extension/src/brain.js', '../extension/src/captions.js', 'chat.js', 'main.js'];
const out = '// AI stand-in, chat only (v1). Paste into the console of your Google Meet tab. Generated by chat-v1/build.mjs; do not edit.\n' +
  parts.map((p) => readFileSync(new URL(p, here), 'utf8')).join('\n');
writeFileSync(new URL('../standin-chat.js', here), out);
console.log(new Date().toISOString() + ' wrote standin-chat.js, ' + out.length + ' bytes from ' + parts.length + ' parts');
