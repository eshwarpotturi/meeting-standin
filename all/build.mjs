// Joins the shared parts into the one file you paste into the Meet tab's console: standin-all.js
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('./', import.meta.url);
const parts = ['../extension/src/log.js', '../extension/src/config.js', '../extension/src/brain.js', '../extension/src/captions.js', '../extension/src/slides.js', '../extension/src/camera.js', '../chat-v1/chat.js', '../extension/src/datachart.js', 'main.js'];
const out = '// AI stand-in, all in one (chat + camera slides + open questions + override). Paste into the console of your Google Meet tab. Generated by all/build.mjs; do not edit.\n' +
  parts.map((p) => readFileSync(new URL(p, here), 'utf8')).join('\n');
writeFileSync(new URL('../standin-all.js', here), out);
console.log(new Date().toISOString() + ' wrote standin-all.js, ' + out.length + ' bytes from ' + parts.length + ' parts');
