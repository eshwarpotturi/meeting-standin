// Joins the shared parts into the one file you paste into the Meet tab's console: standin-all.js
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('./', import.meta.url);
const parts = ['../extension/src/log.js', '../extension/src/config.js', '../extension/src/brain.js', '../extension/src/context.js', '../extension/src/captions.js', '../extension/src/slides.js', '../extension/src/camera.js', '../chat-v1/chat.js', '../extension/src/datachart.js',
  '../extension/src/research.js', 'main.js'];
const out = '// AI stand-in, all in one (chat + camera slides + open questions + override). Paste into the console of your Google Meet tab. Generated by all/build.mjs; do not edit.\n' +
  parts.map((p) => readFileSync(new URL(p, here), 'utf8')).join('\n');
// ASCII only: a paste through Windows PowerShell or Notepad ANSI would garble characters such as the en dash.
const ascii = out.replace(/[^\x00-\x7f]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
writeFileSync(new URL('../standin-all.js', here), ascii);
console.log(new Date().toISOString() + ' wrote standin-all.js, ' + out.length + ' bytes from ' + parts.length + ' parts');
